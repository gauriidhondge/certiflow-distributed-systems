"""
CertiFlow - Certificate Generator Worker
----------------------------------------
Horizontally scalable consumer. Every replica:
  1. atomically moves one job from the queue to a 'processing' list (BLMOVE),
  2. renders a PDF certificate with a QR code,
  3. signs it with HMAC-SHA256 (tamper-proofing),
  4. stores the result in Redis and acknowledges the job.
Run more replicas => more certificates per second.
"""
import base64
import hashlib
import hmac
import io
import json
import os
import signal
import socket
import time

import redis
from reportlab.graphics import renderPDF
from reportlab.graphics.barcode.qr import QrCodeWidget
from reportlab.graphics.shapes import Drawing
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.pdfgen import canvas

r = redis.Redis(
    host=os.getenv("REDIS_HOST", "redis"),
    port=int(os.getenv("REDIS_PORT", "6379")),
    decode_responses=True,
)

QUEUE = "certiflow:jobs"
PROCESSING = "certiflow:processing"
CLAIMS = "certiflow:claims"
STALE_SECONDS = 30
POD = socket.gethostname()
SECRET = os.getenv("SIGNING_SECRET", "change-me").encode()
PUBLIC_URL = os.getenv("PUBLIC_URL", "http://localhost:8080").rstrip("/")
CPU_WORK_MS = int(os.getenv("CPU_WORK_MS", "300"))   # simulated heavy rendering
MAX_ATTEMPTS = 3

NAVY = colors.HexColor("#1F2A44")
GOLD = colors.HexColor("#B8892B")


def log(msg):
    print(f"[worker {POD}] {msg}", flush=True)


def sign(cert):
    payload = f"{cert['cert_id']}|{cert['name']}|{cert['event_name']}|{cert['date']}"
    return hmac.new(SECRET, payload.encode(), hashlib.sha256).hexdigest()[:24]


def burn_cpu(ms):
    """Simulates expensive rendering (high-res templates, fonts, images) so
    that CPU-based autoscaling (HPA) has something to react to."""
    end = time.perf_counter() + ms / 1000
    block = b"x" * 4096
    while time.perf_counter() < end:
        hashlib.sha256(block).digest()


def render_pdf(cert, signature):
    buf = io.BytesIO()
    w, h = landscape(A4)
    c = canvas.Canvas(buf, pagesize=(w, h))
    c.setTitle(f"Certificate {cert['cert_id']}")

    # borders
    c.setStrokeColor(NAVY)
    c.setLineWidth(8)
    c.rect(18, 18, w - 36, h - 36)
    c.setStrokeColor(GOLD)
    c.setLineWidth(2)
    c.rect(32, 32, w - 64, h - 64)

    c.setFillColor(NAVY)
    c.setFont("Helvetica-Bold", 34)
    c.drawCentredString(w / 2, h - 120, "CERTIFICATE")
    c.setFont("Helvetica", 16)
    c.setFillColor(GOLD)
    role = cert.get("role", "Participant").lower()
    if role in ("winner", "runner-up", "runner up", "topper"):
        subtitle = "OF ACHIEVEMENT"
    elif role in ("volunteer", "coordinator", "organiser", "organizer"):
        subtitle = "OF APPRECIATION"
    else:
        subtitle = "OF PARTICIPATION"
    c.drawCentredString(w / 2, h - 145, subtitle)

    c.setFillColor(colors.black)
    c.setFont("Helvetica", 14)
    c.drawCentredString(w / 2, h - 200, "This is to certify that")
    c.setFont("Helvetica-Bold", 30)
    c.setFillColor(NAVY)
    c.drawCentredString(w / 2, h - 245, cert["name"])
    c.setStrokeColor(GOLD)
    c.setLineWidth(1)
    c.line(w / 2 - 200, h - 255, w / 2 + 200, h - 255)

    c.setFillColor(colors.black)
    c.setFont("Helvetica", 14)
    c.drawCentredString(w / 2, h - 290, f"has taken part as {cert.get('role', 'Participant')} in")
    c.setFont("Helvetica-Bold", 18)
    c.drawCentredString(w / 2, h - 318, cert["event_name"])
    c.setFont("Helvetica", 13)
    c.drawCentredString(w / 2, h - 342, f"organised by {cert['organizer']} on {cert['date']}")

    # QR code that links to the public verification page
    verify_url = f"{PUBLIC_URL}/?verify={cert['cert_id']}"
    qr = QrCodeWidget(verify_url)
    x0, y0, x1, y1 = qr.getBounds()
    size = 95
    d = Drawing(size, size, transform=[size / (x1 - x0), 0, 0, size / (y1 - y0), 0, 0])
    d.add(qr)
    renderPDF.draw(d, c, w - 150, 50)

    c.setFont("Helvetica", 8)
    c.setFillColor(colors.grey)
    c.drawString(55, 82, f"Certificate ID: {cert['cert_id']}")
    c.drawString(55, 70, f"Digital signature: {signature}")
    c.drawString(55, 58, f"Verify at {PUBLIC_URL}  |  generated by pod {POD}")

    c.showPage()
    c.save()
    return buf.getvalue()


def process(job):
    cert_id = job["cert_id"]
    key = f"cert:{cert_id}"
    cert = r.hgetall(key)
    if not cert:
        log(f"cert {cert_id} vanished, skipping")
        return
    r.hset(key, "status", "generating")

    burn_cpu(CPU_WORK_MS)
    signature = sign(cert)
    pdf = render_pdf(cert, signature)

    # Idempotency: if a recovered job was already finished by another worker,
    # don't count it twice.
    already_done = r.hget(key, "status") == "generated"
    pipe = r.pipeline()
    pipe.hset(key, mapping={
        "status": "generated",
        "signature": signature,
        "worker": POD,
        "generated_at": time.strftime("%Y-%m-%d %H:%M:%S"),
        "pdf": base64.b64encode(pdf).decode(),
    })
    pipe.hdel(key, "error")
    if not already_done:
        pipe.hincrby(f"event:{cert['event_id']}", "done", 1)
        pipe.incr("stats:generated")
    pipe.hincrby("workers:processed", POD, 1)
    pipe.execute()
    log(f"generated {cert_id} for {cert['name']} ({len(pdf) // 1024} KB)")


def handle_failure(raw, job, err):
    cert_id = job.get("cert_id", "?")
    attempt = int(job.get("attempt", 1))
    log(f"FAILED {cert_id} attempt {attempt}: {err}")
    if attempt < MAX_ATTEMPTS:
        job["attempt"] = attempt + 1
        r.lpush(QUEUE, json.dumps(job))          # retry
    else:
        cert = r.hgetall(f"cert:{cert_id}")
        r.hset(f"cert:{cert_id}", mapping={"status": "failed", "error": str(err)[:200]})
        if cert.get("event_id"):
            r.hincrby(f"event:{cert['event_id']}", "failed", 1)


def reap_stuck_jobs():
    """Crash recovery: if a worker pod died while holding a job (e.g. it was
    force-killed), that job stays in the processing list. Any live worker
    moves jobs older than STALE_SECONDS back to the main queue."""
    now = time.time()
    for raw in r.lrange(PROCESSING, 0, -1):
        claimed_at = r.hget(CLAIMS, raw)
        if claimed_at is None:
            r.hsetnx(CLAIMS, raw, now)       # start the clock for this job
            continue
        if now - float(claimed_at) > STALE_SECONDS:
            if r.lrem(PROCESSING, 1, raw):   # only one worker wins the recovery
                r.hdel(CLAIMS, raw)
                r.lpush(QUEUE, raw)
                log(f"RECOVERED stuck job from a dead worker: {json.loads(raw)['cert_id']}")


running = True


def on_sigterm(*_):
    """Kubernetes sends SIGTERM when a pod is deleted / scaled down.
    Finish the current certificate, then exit cleanly (graceful shutdown)."""
    global running
    running = False
    log("SIGTERM received - finishing current job, then shutting down")


def main():
    signal.signal(signal.SIGTERM, on_sigterm)
    signal.signal(signal.SIGINT, on_sigterm)
    log(f"started, cpu_work={CPU_WORK_MS}ms, public_url={PUBLIC_URL}")
    last_reap = 0.0
    while running:
        try:
            r.zadd("workers:heartbeat", {POD: time.time()})
            if time.time() - last_reap > 10:
                reap_stuck_jobs()
                last_reap = time.time()
            # Atomic hand-off: the job moves to the processing list in one step,
            # so it is never lost even if this pod crashes mid-way.
            raw = r.blmove(QUEUE, PROCESSING, timeout=3, src="RIGHT", dest="LEFT")
            if raw is None:
                continue
            r.hset(CLAIMS, raw, time.time())
            job = json.loads(raw)
            try:
                process(job)
            except Exception as e:  # noqa: BLE001
                handle_failure(raw, job, e)
            finally:
                r.lrem(PROCESSING, 1, raw)
                r.hdel(CLAIMS, raw)
        except redis.RedisError as e:
            log(f"redis unavailable ({e}), retrying in 2s")
            time.sleep(2)
    try:
        r.zrem("workers:heartbeat", POD)
    except redis.RedisError:
        pass
    log("shut down cleanly")


if __name__ == "__main__":
    main()